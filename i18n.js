function getI18nKey(lang) {
    if (I18N[lang]) return lang;
    if (lang === 'no' || lang === 'nb' || lang === 'nn') return 'no';
    const base = lang.split('-')[0];
    if (I18N[base]) return base;
    return 'en';
}

function detectLanguage() {
    const saved = localStorage.getItem('nomad-os-lang');
    const fromSaved = resolveLangCode(saved);
    if (fromSaved) return fromSaved;

    const browser = navigator.language || 'en';
    return resolveLangCode(browser) || resolveLangCode(browser.split('-')[0]) || 'en';
}

let currentLang = detectLanguage();

function t(key) {
    const i18nKey = getI18nKey(currentLang);
    const parts = key.split('.');
    let val = I18N[i18nKey];
    for (const p of parts) {
        val = val?.[p];
    }
    if (val == null) {
        val = I18N.en;
        for (const p of parts) val = val?.[p];
    }
    return val ?? key;
}

function getLocale() {
    return LOCALE_MAP[currentLang] || LOCALE_MAP[currentLang.split('-')[0]] || 'en-US';
}

function getCountryName(code) {
    const named = t(`countries.${code}`);
    if (named && named !== `countries.${code}`) return named;
    return PPP_OVERRIDES?.[code]?.country || (typeof currencyMap !== 'undefined' && currencyMap[code]?.name) || code;
}

function getUnitLabels(unitKey) {
    return t(`units.${unitKey}`) || I18N.en.units[unitKey];
}

function getRegionLabel(region) {
    return t(`regions.${region}`) || REGION_LABELS?.[region] || region;
}

function applyStaticTranslations() {
    const langBase = currentLang.split('-')[0];
    document.documentElement.lang = currentLang === 'no' ? 'no' : langBase;
    document.documentElement.dir = (RTL_LANGS.has(currentLang) || RTL_LANGS.has(langBase)) ? 'rtl' : 'ltr';
    const page = document.body?.dataset?.page;
    if (page === 'hotels') {
        document.title = `${t('hotelPageTitle')} · ${t('logo')}`;
    } else if (page === 'map') {
        document.title = `${t('mapPageTitle')} · ${t('logo')}`;
    } else {
        document.title = t('pageTitle');
    }

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        el.textContent = t(el.dataset.i18n);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        el.placeholder = t(el.dataset.i18nPlaceholder);
    });

    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
        el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });

    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
        el.setAttribute('title', t(el.dataset.i18nTitle));
    });

    const abbr = document.querySelector('.ppp-help abbr');
    if (abbr) abbr.title = t('pppAbbrTitle');

    document.querySelectorAll('.ppp-unit').forEach((card) => {
        const key = card.dataset.unit;
        const labels = getUnitLabels(key);
        if (!labels) return;
        const nameEl = card.querySelector('.ppp-unit__name');
        const descEl = card.querySelector('.ppp-unit__desc');
        if (nameEl) nameEl.textContent = labels.name;
        if (descEl) descEl.textContent = labels.desc;
    });

    const langSelect = document.getElementById('lang-select');
    if (langSelect) langSelect.value = currentLang;
}

function setLanguage(lang) {
    const resolved = resolveLangCode(lang);
    if (!resolved) return;
    currentLang = resolved;
    localStorage.setItem('nomad-os-lang', resolved);
    applyStaticTranslations();
    if (typeof onLanguageChange === 'function') onLanguageChange();
}

function initLanguagePicker() {
    const select = document.getElementById('lang-select');
    if (!select) return;

    select.innerHTML = LANG_OPTIONS.map(
        ({ code, flag, label }) => `<option value="${code}">${flag} ${label}</option>`
    ).join('');
    select.value = LANG_BY_CODE[currentLang] ? currentLang : resolveLangCode(currentLang) || 'en';

    if (select.dataset.langInit) return;
    select.dataset.langInit = '1';

    select.addEventListener('change', () => {
        setLanguage(select.value);
    });
}
